# Paths
BASE_DIR = Path(__file__).resolve().parent.parent
MODEL_PATH = BASE_DIR / "models" / "atm_failure_model.pkl"
DATA_PATH = BASE_DIR / "data" / "atm_data.csv"
FRONTEND_DIR = BASE_DIR / "frontend"

# Import explanation engine and LangChain analysis
